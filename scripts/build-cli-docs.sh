#!/usr/bin/env bash
# Builds the CLI documentation site (cli-docs/ → docs/cli/, served at https://rajumark.github.io/sextant/cli/).
# Regenerates the reference pages that come from the code (command help, index schema) first, so they never drift.
#
#   scripts/build-cli-docs.sh            # needs mkdocs on PATH: pip install -r cli-docs/requirements.txt
#   MKDOCS=/path/to/mkdocs scripts/build-cli-docs.sh
#   scripts/build-cli-docs.sh --serve    # live preview on http://127.0.0.1:8000
set -euo pipefail
cd "$(dirname "$0")/.."

MKDOCS="${MKDOCS:-mkdocs}"
SEXTANT=cli/build/install/sextant/bin/sextant
[ -x "$SEXTANT" ] || gradle -q :cli:installShadowDist
REF=cli-docs/content/reference

# --- Command reference, from each command's --help -------------------------------------------------------------
{
  echo "# Commands"
  echo
  echo "<!-- Generated by scripts/build-cli-docs.sh from \`sextant <command> --help\`. Do not edit by hand. -->"
  echo
  echo "Every command prints help with \`-h\` / \`--help\`. Commands that read an extraction take the output folder;"
  echo "\`info\` and \`icon\` also accept an APK directly. Progress and errors go to stderr, results to stdout."
  echo
  echo '```text'
  "$SEXTANT" --help
  echo '```'
  commands=$("$SEXTANT" --help | awk '/^Commands:/{on=1;next} on && /^  [a-z]/{print $1}')
  for cmd in $commands; do
    echo
    echo "## $cmd"
    echo
    echo '```text'
    "$SEXTANT" "$cmd" --help
    echo '```'
  done
} > "$REF/commands.md"

# --- Index schema, from IndexSchema.DDL ------------------------------------------------------------------------
{
  echo "# SQLite index schema"
  echo
  echo "<!-- Generated by scripts/build-cli-docs.sh from core/…/index/IndexSchema.kt. Do not edit by hand. -->"
  echo
  echo "\`index.sqlite\` holds everything in the output folder, normalized. Every method reference (defined in the APK"
  echo "or external) has one row in \`methods\`; edges point at integer ids, and the views \`call_edges\`, \`string_uses\`"
  echo "and \`search_items\` give the readable, descriptor-based form. JSON arrays are stored as TEXT; use SQLite's"
  echo "\`json_each\` to expand them. Query it with \`sextant sql <dir> \"…\"\` (read-only) or any SQLite tool."
  echo
  echo "Schema version: **$(sed -n 's/.*const val VERSION = \([0-9]*\).*/\1/p' core/src/main/kotlin/io/github/rajumark/sextant/core/index/IndexSchema.kt)**"
  echo "(stored in \`meta\` as \`index_schema_version\`)."
  echo
  echo '```sql'
  awk '/val DDL =/{f=1;next} f && /"""\.trimIndent/{exit} f && !/"""/' \
    core/src/main/kotlin/io/github/rajumark/sextant/core/index/IndexSchema.kt | sed 's/^        //'
  echo '```'
  echo
  echo "Indexes created after loading:"
  echo
  echo '```sql'
  awk '/val INDEXES =/{f=1;next} f && /"""\.trimIndent/{exit} f && !/"""/' \
    core/src/main/kotlin/io/github/rajumark/sextant/core/index/IndexSchema.kt | sed 's/^        //'
  echo '```'
} > "$REF/index-schema.md"

if [ "${1:-}" = "--serve" ]; then
  exec "$MKDOCS" serve -f cli-docs/mkdocs.yml
fi
"$MKDOCS" build --strict -f cli-docs/mkdocs.yml
touch docs/.nojekyll
echo "built docs/cli/"
